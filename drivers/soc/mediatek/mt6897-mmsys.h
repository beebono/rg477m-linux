#ifndef __SOC_MEDIATEK_MT6897_MMSYS_H
#define __SOC_MEDIATEK_MT6897_MMSYS_H

#include <linux/bits.h>
#include <linux/soc/mediatek/mtk-mmsys.h>

/*
 * MT6897 (MT6985 generation) display routing.
 *
 * The overlay engines live in OVLSYS0 (config at 0x14400000) and reach
 * DISPSYS0 (config at 0x14000000) through the OVLSYS DLO_ASYNC3 ->
 * DISPSYS DLI_ASYNC0 relay pair, which is hard-wired and needs no routing
 * register. Register offsets and bit names follow the downstream
 * mediatek_v2 driver (mtk_drm_ddp.c, MT6897_* / MT6985_* definitions; the
 * MT6897 routing helpers use the MT6985 layout).
 *
 * Every crossbar register is a set of MOUT enable bits in [15:0]; bits
 * [31:16] read back the active (post-shadow) value. Only the low bits are
 * ever written here.
 */

/* --- OVLSYS0 config (0x14400000) --- */
#define MT6897_OVLSYS_BYPASS_MUX_SHADOW		0xf00
#define MT6897_OVLSYS_OVL_CON			0xf08
#define MT6897_OVL0_2L_TO_BLEND_CROSSBAR0		BIT(0)
#define MT6897_OVL_BG_CROSSBAR0_MOUT_EN		0xf10
#define MT6897_OVL_BG_CROSSBAR1_MOUT_EN		0xf14
#define MT6897_OVL_BLEND_CROSSBAR0_MOUT_EN	0xf38
#define MT6897_OVL0_2L_TO_DLO_RELAY3			BIT(0)
#define MT6897_OVL_BLEND_CROSSBAR2_MOUT_EN	0xf40

/* --- DISPSYS0 config (0x14000000) --- */
#define MT6897_DISPSYS_BYPASS_MUX_SHADOW	0xc30
#define MT6897_BYPASS_MUX_SHADOW_ALL		(GENMASK(23, 16) | BIT(0))
#define MT6897_COMP_OUT_CROSSBAR3_MOUT_EN	0xeac
#define MT6897_PANEL_COMP_OUT_CROSSBAR3_TO_MERGE_OUT_CROSSBAR0	BIT(0)
#define MT6897_MERGE_OUT_CROSSBAR0_MOUT_EN	0xf0c
#define MT6897_COMP_OUT_CROSSBAR0_TO_DSI0		BIT(0)
#define MT6897_PANEL_COMP_OUT_CROSSBAR0_MOUT_EN	0xf48
#define MT6897_PANEL_COMP_OUT_CROSSBAR1_MOUT_EN	0xf4c
#define MT6897_PQ_OUT_CROSSBAR1_TO_COMP_OUT_CROSSBAR3	BIT(3)
#define MT6897_PANEL_COMP_OUT_CROSSBAR3_SEL_IN	0xf68
#define MT6897_COMP_OUT_CROSSBAR3_SEL_PANEL_COMP_OUT_CROSSBAR1	1
#define MT6897_PQ_IN_CROSSBAR0_MOUT_EN		0xf74
#define MT6897_DLI_RELAY0_TO_PQ_OUT_CROSSBAR3		BIT(2)
#define MT6897_PQ_OUT_CROSSBAR3_MOUT_EN		0xfa4
#define MT6897_PQ_IN_CROSSBAR2_TO_PANEL_COMP_OUT_CROSSBAR1	BIT(1)

/*
 * OVLSYS0: OVL0_2L -> BLEND_CROSSBAR0 -> DLO_RELAY3 (DLO_ASYNC3).
 *
 * The bootloader cascades OVL0_2L -> OVL1_2L -> OVL2_2L through the
 * background crossbars and leaves OVL2_2L driving DLO_RELAY3; those links are
 * cleared here so that DLO_RELAY3 has a single source and no crossbar output
 * waits on an engine outside our mutex.
 */
static const struct mtk_mmsys_routes mmsys_mt6897_ovlsys_routing_table[] = {
	{
		DDP_COMPONENT_OVL_2L0, DDP_COMPONENT_OVLSYS_DLO_ASYNC3,
		MT6897_OVLSYS_OVL_CON, GENMASK(7, 0),
		MT6897_OVL0_2L_TO_BLEND_CROSSBAR0
	}, {
		DDP_COMPONENT_OVL_2L0, DDP_COMPONENT_OVLSYS_DLO_ASYNC3,
		MT6897_OVL_BG_CROSSBAR0_MOUT_EN, GENMASK(4, 0), 0
	}, {
		DDP_COMPONENT_OVL_2L0, DDP_COMPONENT_OVLSYS_DLO_ASYNC3,
		MT6897_OVL_BG_CROSSBAR1_MOUT_EN, GENMASK(4, 0), 0
	}, {
		DDP_COMPONENT_OVL_2L0, DDP_COMPONENT_OVLSYS_DLO_ASYNC3,
		MT6897_OVL_BLEND_CROSSBAR0_MOUT_EN, GENMASK(6, 0),
		MT6897_OVL0_2L_TO_DLO_RELAY3
	}, {
		DDP_COMPONENT_OVL_2L0, DDP_COMPONENT_OVLSYS_DLO_ASYNC3,
		MT6897_OVL_BLEND_CROSSBAR2_MOUT_EN, GENMASK(6, 0), 0
	},
};

/*
 * DISPSYS0, PQ bypass (downstream DRM_BYPASS_PQ main path):
 * DLI_ASYNC0 -> PQ_IN_CROSSBAR0 -> PQ_OUT_CROSSBAR3 -> PANEL_COMP_OUT_CROSSBAR1
 * -> COMP_OUT_CROSSBAR3 -> MERGE_OUT_CROSSBAR0 -> DSI0.
 *
 * The bootloader runs the full PQ chain (PQ_IN_CROSSBAR0 -> RSZ0 ... ->
 * POSTALIGN0 -> PANEL_COMP_OUT_CROSSBAR0 -> COMP_OUT_CROSSBAR3) with CHIST
 * taps; the PQ engines have no driver here, so the chain is bypassed and its
 * entry/exit links into our path are cleared.
 */
static const struct mtk_mmsys_routes mmsys_mt6897_dispsys_routing_table[] = {
	{
		DDP_COMPONENT_DLI_ASYNC0, DDP_COMPONENT_DSI0,
		MT6897_PQ_IN_CROSSBAR0_MOUT_EN, GENMASK(3, 0),
		MT6897_DLI_RELAY0_TO_PQ_OUT_CROSSBAR3
	}, {
		DDP_COMPONENT_DLI_ASYNC0, DDP_COMPONENT_DSI0,
		MT6897_PQ_OUT_CROSSBAR3_MOUT_EN, GENMASK(5, 0),
		MT6897_PQ_IN_CROSSBAR2_TO_PANEL_COMP_OUT_CROSSBAR1
	}, {
		DDP_COMPONENT_DLI_ASYNC0, DDP_COMPONENT_DSI0,
		MT6897_PANEL_COMP_OUT_CROSSBAR1_MOUT_EN, GENMASK(5, 0),
		MT6897_PQ_OUT_CROSSBAR1_TO_COMP_OUT_CROSSBAR3
	}, {
		DDP_COMPONENT_DLI_ASYNC0, DDP_COMPONENT_DSI0,
		MT6897_PANEL_COMP_OUT_CROSSBAR0_MOUT_EN, GENMASK(5, 0), 0
	}, {
		DDP_COMPONENT_DLI_ASYNC0, DDP_COMPONENT_DSI0,
		MT6897_PANEL_COMP_OUT_CROSSBAR3_SEL_IN, GENMASK(2, 0),
		MT6897_COMP_OUT_CROSSBAR3_SEL_PANEL_COMP_OUT_CROSSBAR1
	}, {
		DDP_COMPONENT_DLI_ASYNC0, DDP_COMPONENT_DSI0,
		MT6897_COMP_OUT_CROSSBAR3_MOUT_EN, GENMASK(7, 0),
		MT6897_PANEL_COMP_OUT_CROSSBAR3_TO_MERGE_OUT_CROSSBAR0
	}, {
		DDP_COMPONENT_DLI_ASYNC0, DDP_COMPONENT_DSI0,
		MT6897_MERGE_OUT_CROSSBAR0_MOUT_EN, GENMASK(6, 0),
		MT6897_COMP_OUT_CROSSBAR0_TO_DSI0
	},
};

#endif /* __SOC_MEDIATEK_MT6897_MMSYS_H */

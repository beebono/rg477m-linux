static int ft8201p_prepare(struct drm_panel *panel)
{
	struct ft8201p_panel *ctx = to_ft8201p(panel);
	struct device *dev = &ctx->dsi->dev;
	int ret;

	/* BRINGUP(rg477m) */
	dev_info(dev, "bringup: panel prepare: reset + init sequence\n");

	ft8201p_reset(ctx);

	ret = ft8201p_init(ctx);
	if (ret < 0) {
		dev_err(dev, "bringup: panel init sequence failed: %d\n", ret);
		return ret;
	}

	dev_info(dev, "bringup: panel prepare done (sleep out, display on)\n");
	return 0;
}

static int ft8201p_unprepare(struct drm_panel *panel)
{
	struct ft8201p_panel *ctx = to_ft8201p(panel);
	struct mipi_dsi_multi_context dsi_ctx = { .dsi = ctx->dsi };

	dev_info(&ctx->dsi->dev, "bringup: panel unprepare: display off, sleep in\n");

	/* supplies and reset are left alone, see the header comment */
	mipi_dsi_dcs_set_display_off_multi(&dsi_ctx);
	mipi_dsi_msleep(&dsi_ctx, 20);
	mipi_dsi_dcs_enter_sleep_mode_multi(&dsi_ctx);
	mipi_dsi_msleep(&dsi_ctx, 120);

	if (dsi_ctx.accum_err)
		dev_warn(&ctx->dsi->dev, "display off/sleep in failed: %d\n",
			 dsi_ctx.accum_err);

	return 0;
}


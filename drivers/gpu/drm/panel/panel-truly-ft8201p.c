/*
 * Truly FT8201P (FocalTech FT8201P TDDI) 1280x960 MIPI-DSI video mode panel,
 * as fitted to the Anbernic RG477M.
 *
 * The initialisation sequence is the vendor one, verbatim (recovered from the
 * vendor kernel module panel-truly-ft8201p-vdo-120hz.ko): entries whose first
 * byte is below 0xb0 are DCS writes, the others generic writes, then sleep
 * out and display on with 200 ms each.
 *
 * Power: the panel's supplies (VDD 3.0 V from the PMIC, and the 1.8 V/bias
 * enables on GPIO64/GPIO63 that also feed an I2C-programmed bias IC) are left
 * exactly as the bootloader set them. This driver does not request them and
 * never switches them; prepare only pulses the reset line and sends the init
 * sequence, unprepare only sends display off and sleep in.
 *
 * Lane rate: the vendor driver fixes the lane clock at 585 MHz (1170 Mbps per
 * lane, above the 1092 Mbps the 182 MHz pixel clock needs); it is passed to
 * the host as hs_rate.
 */


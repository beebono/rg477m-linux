static int ft8201p_get_modes(struct drm_panel *panel,
			     struct drm_connector *connector)
{
	static const u32 bus_format = MEDIA_BUS_FMT_RGB888_1X24;
	unsigned int i;

	for (i = 0; i < ARRAY_SIZE(ft8201p_modes); i++) {
		struct drm_display_mode *mode;

		mode = drm_mode_duplicate(connector->dev, &ft8201p_modes[i]);
		if (!mode)
			return -ENOMEM;

		drm_mode_set_name(mode);
		mode->type = ft8201p_modes[i].type;
		drm_mode_probed_add(connector, mode);
	}

	connector->display_info.width_mm = ft8201p_modes[0].width_mm;
	connector->display_info.height_mm = ft8201p_modes[0].height_mm;
	connector->display_info.bpc = 8;
	drm_display_info_set_bus_formats(&connector->display_info, &bus_format, 1);

	return ARRAY_SIZE(ft8201p_modes);
}

